-- 每日小挑戰（成語島）：自家題庫 + 每日挑戰成績。
-- 題目為自編（日常常用、常混淆字），不含任何外部詞表內容。
-- 成績存獨立新表 chengyu_family_challenge_attempts，不寫 chengyu_family_attempts，
-- 因此不會觸發既有 XP 核算與 learning_adventure 金幣觸發器（星星/獎勵規則不變）。
-- 兩表沿用家庭雲慣例：預設 RLS、撤銷 public/anon/authenticated，只開 service_role。

create table if not exists public.chengyu_family_challenge_items(
  id uuid primary key default gen_random_uuid(),
  mode text not null check (mode in ('typo','pairing')),
  level text not null check (level in ('國小','國中','進階')),
  payload jsonb not null,
  active boolean not null default true,
  created_at timestamptz not null default clock_timestamp()
);
alter table public.chengyu_family_challenge_items enable row level security;
revoke all on public.chengyu_family_challenge_items from public,anon,authenticated;
grant select on public.chengyu_family_challenge_items to service_role;

create table if not exists public.chengyu_family_challenge_attempts(
  id uuid primary key default gen_random_uuid(),
  family_id uuid not null references public.chengyu_family_spaces(id) on delete cascade,
  learner_id uuid not null references public.chengyu_family_learners(id) on delete cascade,
  challenge_date date not null,
  question_count integer not null check (question_count > 0),
  correct_count integer not null check (correct_count >= 0),
  answers jsonb not null,
  created_at timestamptz not null default clock_timestamp()
);
alter table public.chengyu_family_challenge_attempts enable row level security;
revoke all on public.chengyu_family_challenge_attempts from public,anon,authenticated;
grant select,insert on public.chengyu_family_challenge_attempts to service_role;
-- 每位玩家每天一筆（重玩只更新本地狀態，不重複入庫）
create unique index if not exists chengyu_family_challenge_attempts_daily
  on public.chengyu_family_challenge_attempts(family_id,learner_id,challenge_date);

