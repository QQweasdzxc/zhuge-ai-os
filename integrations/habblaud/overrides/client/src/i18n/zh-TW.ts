/** Portuguese activity text originates upstream; display a truthful zh-TW summary by event kind. */
export function zhTwActivityText(activity: Pick<Activity, 'id' | 'kind' | 'tool'>): string {
  if (activity.id.startsWith('social:')) return '虛擬角色生活互動';
  const label = ACTIVITY_LABELS[activity.kind];
  const tool = activity.tool?.trim();
  return tool && /^[A-Za-z][A-Za-z0-9_.-]{0,39}$/.test(tool) ? `${label}｜${tool}` : label;
}

/** Translate the activity summary only; user-authored prompts and transcripts stay untouched. */
export function activityTextForLocale(activity: Activity): string {
  return getLocale() === 'zh-TW' ? zhTwActivityText(activity) : activity.text;
}

/** Upstream detail text can be Portuguese or contain raw command context. Do not leak it into zh-TW status UI. */
export function activityDetailForLocale(activity: Pick<Activity, 'detail'>): string | undefined {
  return getLocale() === 'zh-TW' ? undefined : activity.detail;
}
